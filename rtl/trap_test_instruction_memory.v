module trap_test_instruction_memory (
    input [31:0] address,
    output reg [31:0] instruction
);

always @(*) begin

    case (address)

        // -----------------------------------------------------
        // x1 = 0x100
        // -----------------------------------------------------

        32'h00000000:
            instruction = 32'h10000093;

        // -----------------------------------------------------
        // CSRRW x0, mtvec, x1
        // -----------------------------------------------------

        32'h00000004:
            instruction = 32'h30509073;

        // -----------------------------------------------------
        // ECALL
        // -----------------------------------------------------

        32'h00000008:
            instruction = 32'h00000073;

        // -----------------------------------------------------
        // Trap handler
        // -----------------------------------------------------

        32'h00000100:
            instruction = 32'h342022F3;

        32'h00000104:
            instruction = 32'h34102373;

        // -----------------------------------------------------
        // MRET
        // -----------------------------------------------------

        32'h00000108:
            instruction = 32'h30200073;

        default:
            instruction = 32'h00000013;

    endcase

end

endmodule