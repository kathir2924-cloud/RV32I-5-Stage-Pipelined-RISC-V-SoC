module instruction_memory (
    input  [31:0] address,
    output reg [31:0] instruction
);

always @(*) begin
    case (address)

        // =========================================================
        // ADDI
        // =========================================================

        32'd0:   instruction = 32'h00A00093; // ADDI x1,x0,10
        32'd4:   instruction = 32'h01400113; // ADDI x2,x0,20


        // =========================================================
        // R-TYPE
        // =========================================================

        32'd8:   instruction = 32'h002081B3; // ADD x3,x1,x2
        32'd12:  instruction = 32'h40110233; // SUB x4,x2,x1
        32'd16:  instruction = 32'h0020F2B3; // AND x5,x1,x2
        32'd20:  instruction = 32'h0020E333; // OR  x6,x1,x2
        32'd24:  instruction = 32'h0020C3B3; // XOR x7,x1,x2


        // =========================================================
        // STORE / LOAD
        // =========================================================

        32'd28:  instruction = 32'h00302023; // SW x3,0(x0)
        32'd32:  instruction = 32'h00002403; // LW x8,0(x0)


        // =========================================================
        // LOAD-USE
        // =========================================================

        32'd36:  instruction = 32'h001404B3; // ADD x9,x8,x1


        // =========================================================
        // SLT / SLTU
        // =========================================================

        32'd40:  instruction = 32'h0020A533; // SLT  x10,x1,x2
        32'd44:  instruction = 32'h0020B5B3; // SLTU x11,x1,x2


        // =========================================================
        // BEQ
        // =========================================================

        // x1 == x2 is FALSE
        // Therefore branch should NOT be taken.

        32'd48:  instruction = 32'h00208663; // BEQ x1,x2,+12

        // These must execute
        32'd52:  instruction = 32'h06F00613; // x12=111
        32'd56:  instruction = 32'h0DE00613; // x12=222

        32'd60:  instruction = 32'h30900613; // x12=777


        // =========================================================
        // JAL
        // =========================================================

        // PC=64
        // JAL x13,+16
        // target=80
        // link=68

        32'd64:  instruction = 32'h010006EF; // JAL x13,+16

        // Wrong path
        32'd68:  instruction = 32'h06F00713; // x14=111
        32'd72:  instruction = 32'h0DE00713; // x14=222
        32'd76:  instruction = 32'h14D00713; // x14=333

        // Target
        32'd80:  instruction = 32'h3E700713; // x14=999


        // =========================================================
        // JALR
        // =========================================================

        32'd84:  instruction = 32'h06400793; // ADDI x15,x0,100

        // PC=88
        // target=104
        // link=92

        32'd88:  instruction = 32'h00478867; // JALR x16,x15,4

        // Wrong path
        32'd92:  instruction = 32'h06F00813; // x16=111
        32'd96:  instruction = 32'h0DE00813; // x16=222
        32'd100: instruction = 32'h14D00813; // x16=333

        // Target
        32'd104: instruction = 32'h3E700813; // x16=999


        // =========================================================
        // DEFAULT NOP
        // =========================================================

        default:
            instruction = 32'h00000013;

    endcase
end

endmodule