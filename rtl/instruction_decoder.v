module instruction_decoder (
    input  [31:0] instruction,

    output [4:0] rs1,
    output [4:0] rs2,
    output [4:0] rd,

    output [6:0] opcode,
    output [2:0] func3,
    output [6:0] func7,

    output reg [3:0] alu_op,
    output reg [2:0] imm_type
);


// =============================================================
// INSTRUCTION FIELD EXTRACTION
// =============================================================

assign opcode = instruction[6:0];

assign rd     = instruction[11:7];

assign func3  = instruction[14:12];

assign rs1    = instruction[19:15];

assign rs2    = instruction[24:20];

assign func7  = instruction[31:25];


// =============================================================
// ALU OPERATION CODES
// =============================================================
//
// 0000 = ADD
// 0001 = SUB
// 0010 = AND
// 0011 = OR
// 0100 = XOR
// 0101 = SLL
// 0110 = SRL
// 0111 = SRA
// 1000 = SLT
// 1001 = SLTU
//
// =============================================================


// =============================================================
// IMMEDIATE TYPE CODES
// =============================================================
//
// 000 = I-type
// 001 = S-type
// 010 = B-type
// 011 = U-type
// 100 = J-type
//
// =============================================================


always @(*) begin

    // ---------------------------------------------------------
    // DEFAULT VALUES
    // ---------------------------------------------------------

    alu_op   = 4'b0000;
    imm_type = 3'b000;


    case (opcode)


        // =====================================================
        // R-TYPE
        // Opcode = 0110011
        // =====================================================

        7'b0110011: begin

            case (func3)

                // -------------------------------------------------
                // ADD / SUB
                // -------------------------------------------------

                3'b000: begin

                    if (func7 == 7'b0100000)
                        alu_op = 4'b0001;       // SUB

                    else
                        alu_op = 4'b0000;       // ADD

                end


                // -------------------------------------------------
                // SLL
                // -------------------------------------------------

                3'b001: begin
                    alu_op = 4'b0101;
                end


                // -------------------------------------------------
                // SLT
                // -------------------------------------------------

                3'b010: begin
                    alu_op = 4'b1000;
                end


                // -------------------------------------------------
                // SLTU
                // -------------------------------------------------

                3'b011: begin
                    alu_op = 4'b1001;
                end


                // -------------------------------------------------
                // XOR
                // -------------------------------------------------

                3'b100: begin
                    alu_op = 4'b0100;
                end


                // -------------------------------------------------
                // SRL / SRA
                // -------------------------------------------------

                3'b101: begin

                    if (func7 == 7'b0100000)
                        alu_op = 4'b0111;       // SRA

                    else
                        alu_op = 4'b0110;       // SRL

                end


                // -------------------------------------------------
                // OR
                // -------------------------------------------------

                3'b110: begin
                    alu_op = 4'b0011;
                end


                // -------------------------------------------------
                // AND
                // -------------------------------------------------

                3'b111: begin
                    alu_op = 4'b0010;
                end


                default: begin
                    alu_op = 4'b0000;
                end

            endcase

        end


        // =====================================================
        // I-TYPE ALU
        // Opcode = 0010011
        // =====================================================

        7'b0010011: begin

            imm_type = 3'b000;


            case (func3)

                // -------------------------------------------------
                // ADDI
                // -------------------------------------------------

                3'b000: begin
                    alu_op = 4'b0000;
                end


                // -------------------------------------------------
                // SLLI
                // -------------------------------------------------

                3'b001: begin
                    alu_op = 4'b0101;
                end


                // -------------------------------------------------
                // SLTI
                // -------------------------------------------------

                3'b010: begin
                    alu_op = 4'b1000;
                end


                // -------------------------------------------------
                // SLTIU
                // -------------------------------------------------

                3'b011: begin
                    alu_op = 4'b1001;
                end


                // -------------------------------------------------
                // XORI
                // -------------------------------------------------

                3'b100: begin
                    alu_op = 4'b0100;
                end


                // -------------------------------------------------
                // SRLI / SRAI
                // -------------------------------------------------

                3'b101: begin

                    if (func7 == 7'b0100000)
                        alu_op = 4'b0111;       // SRAI

                    else
                        alu_op = 4'b0110;       // SRLI

                end


                // -------------------------------------------------
                // ORI
                // -------------------------------------------------

                3'b110: begin
                    alu_op = 4'b0011;
                end


                // -------------------------------------------------
                // ANDI
                // -------------------------------------------------

                3'b111: begin
                    alu_op = 4'b0010;
                end


                default: begin
                    alu_op = 4'b0000;
                end

            endcase

        end


        // =====================================================
        // LOAD
        // Opcode = 0000011
        // =====================================================

        7'b0000011: begin

            imm_type = 3'b000;

            // Address calculation:
            // rs1 + immediate

            alu_op = 4'b0000;

        end


        // =====================================================
        // STORE
        // Opcode = 0100011
        // =====================================================

        7'b0100011: begin

            imm_type = 3'b001;

            // Address calculation:
            // rs1 + immediate

            alu_op = 4'b0000;

        end


        // =====================================================
        // CONDITIONAL BRANCH
        // Opcode = 1100011
        // =====================================================

        7'b1100011: begin

            imm_type = 3'b010;

            // Branch comparison path
            // Uses SUB operation in current datapath

            alu_op = 4'b0001;

        end


        // =====================================================
        // LUI
        // Opcode = 0110111
        // =====================================================

        7'b0110111: begin

            imm_type = 3'b011;

            alu_op = 4'b0000;

        end


        // =====================================================
        // AUIPC
        // Opcode = 0010111
        // =====================================================

        7'b0010111: begin

            imm_type = 3'b011;

            alu_op = 4'b0000;

        end


        // =====================================================
        // JAL
        // Opcode = 1101111
        // =====================================================

        7'b1101111: begin

            imm_type = 3'b100;

            alu_op = 4'b0000;

        end


        // =====================================================
        // JALR
        // Opcode = 1100111
        // =====================================================

        7'b1100111: begin

            imm_type = 3'b000;

            alu_op = 4'b0000;

        end


        // =====================================================
        // UNKNOWN / NOP
        // =====================================================

        default: begin

            alu_op   = 4'b0000;
            imm_type = 3'b000;

        end

    endcase

end

endmodule