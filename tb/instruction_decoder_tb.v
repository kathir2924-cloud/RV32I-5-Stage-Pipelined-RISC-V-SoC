`timescale 1ns/1ps

module instruction_decoder_testbench;

reg [31:0] instruction;

wire [4:0] rs1;
wire [4:0] rs2;
wire [4:0] rd;

wire [6:0] opcode;
wire [2:0] func3;
wire [6:0] func7;

wire [3:0] alu_op;
wire [2:0] imm_type;

instruction_decoder dut (
    .instruction(instruction),

    .rs1(rs1),
    .rs2(rs2),
    .rd(rd),

    .opcode(opcode),
    .func3(func3),
    .func7(func7),

    .alu_op(alu_op),
    .imm_type(imm_type)
);

initial begin

    $monitor("Time=%0t | Instruction=%h | Opcode=%b | rs1=%d | rs2=%d | rd=%d | Func3=%b | Func7=%b | ALU_OP=%b | IMM_TYPE=%b",
             $time,
             instruction,
             opcode,
             rs1,
             rs2,
             rd,
             func3,
             func7,
             alu_op,
             imm_type);

    // ==========================================
    // ADD x3, x1, x2
    // ==========================================
    instruction = 32'h002081B3;
    #10;

    // ==========================================
    // SUB x3, x1, x2
    // ==========================================
    instruction = 32'h402081B3;
    #10;

    // ==========================================
    // AND x3, x1, x2
    // ==========================================
    instruction = 32'h0020F1B3;
    #10;

    // ==========================================
    // OR x3, x1, x2
    // ==========================================
    instruction = 32'h0020E1B3;
    #10;

    // ==========================================
    // XOR x3, x1, x2
    // ==========================================
    instruction = 32'h0020C1B3;
    #10;

    // ==========================================
    // ADDI x3, x1, 10
    // ==========================================
    instruction = 32'h00A08193;
    #10;

    // ==========================================
    // LW x3, 4(x1)
    // ==========================================
    instruction = 32'h0040A183;
    #10;

    // ==========================================
    // SW x3, 4(x1)
    // ==========================================
    instruction = 32'h0030A223;
    #10;

    // ==========================================
    // BEQ x1, x2, offset
    // ==========================================
    instruction = 32'h00208063;
    #10;

    // ==========================================
    // LUI x3, immediate
    // ==========================================
    instruction = 32'h123451B7;
    #10;

    // ==========================================
    // AUIPC x3, immediate
    // ==========================================
    instruction = 32'h12345197;
    #10;

    // ==========================================
    // JAL x3, offset
    // ==========================================
    instruction = 32'h008001EF;
    #10;

    // ==========================================
    // JALR x3, 4(x1)
    // ==========================================
    instruction = 32'h004081E7;
    #10;

    $finish;

end

endmodule